//-------------------------------------------------------------------------
// Constructor
//-------------------------------------------------------------------------
TestCmd::TestCmd() :
CATStateCommand ("TestCmd", CATDlgEngOneShot, CATCommandModeShared)
//  Valid states are CATDlgEngOneShot and CATDlgEngRepeat
,_Indication(NULL)
{
	_test = new TestDlg(CATApplicationFrame::GetFrame()->GetMainWindow(), "TestDlg");
	_test->Build();

	// 按显示器（屏幕）分辨率设置对话框默认大小并居中：
	// SetRectDimensions 参数顺序：左上角 X、左上角 Y、高度、宽度（像素）。
	{
		int screenW = GetSystemMetrics(SM_CXSCREEN);
		int screenH = GetSystemMetrics(SM_CYSCREEN);
		int dlgW = screenW * 6 / 10; // 宽度取屏幕的 %
		int dlgH = screenH * 5 / 10; // 高度取屏幕的 %
		if (dlgW < 1200)
			dlgW = 1200; 
		_test->SetRectDimensions(
			(screenW - dlgW) / 2,
			(screenH - dlgH) / 2,
			dlgH,
			dlgW);
	}
}

//-------------------------------------------------------------------------
// Destructor
//-------------------------------------------------------------------------
TestCmd::~TestCmd()
{
	// 销毁 Qt 树表(内部会自动解除窗口父子关系)。
	_treeTableHost.Destroy();

	if (_test != NULL)
	{
		_test->SetVisibility(CATDlgHide);
		_test->RequestDelayedDestruction();
		_test = NULL;
	}
	if (_Indication != NULL)
		_Indication->RequestDelayedDestruction();
}


//-------------------------------------------------------------------------
// BuildGraph()
//-------------------------------------------------------------------------
void TestCmd::BuildGraph()
{
	_test->SetVisibility(CATDlgShow);

// TODO: Define the StateChart
// ---------------------------
	_Indication = new CATIndicationAgent ("Indication");
	CATMathPlane PlaneXY;
	_Indication->SetMathPlane (PlaneXY);
	CATDialogState * initialState = GetInitialState("initialState");
	initialState->AddDialogAgent (_Indication);

	AddTransition( initialState, initialState,
		IsOutputSetCondition (_Indication),
		Action ((ActionMethod) &TestCmd::ActionOne));

	// 对话框尺寸变化时挂载/缩放 Qt 树表。
	AddAnalyseNotificationCB(_test, _test->GetWindSizeNotification(),
		(CATCommandMethod)&TestCmd::OnDialogSizeChanged, NULL);
}

