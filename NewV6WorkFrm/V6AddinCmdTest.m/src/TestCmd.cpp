//-------------------------------------------------------------------------
// EnsureTreeTableAttached()
//-------------------------------------------------------------------------
void TestCmd::EnsureTreeTableAttached()
{
	if (!_treeTableHost.IsAttached())
	{
		CATDlgFrame *host = _test->GetQtTreeTableHost();
		if (!_treeTableHost.Attach(host))
		{
			// 对话框 HWND 尚未创建时直接返回,在下次尺寸通知中再次尝试。
			return;
		}

		ConfigureTreeTable();
	}

	_treeTableHost.Resize();
}

