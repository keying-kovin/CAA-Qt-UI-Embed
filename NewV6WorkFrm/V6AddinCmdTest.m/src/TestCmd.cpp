CATBoolean TestCmd::ActionOne( void *data )
{
	if (_Indication != NULL)
		_Indication->InitializeAcquisition();

	// 数据来源 b):响应事件后程序化填充树数据。
	// 业务场景:视图点击、PLM 查询、命令回调等事件发生后,
	// 把结果构造成 QtTreeNode 数组调用 SetData() 即可刷新树表。
	static const char *kChildCells[9] =
	{
		"事件响应子任务", "EVT-001-01", "李四",
		"2026-08-07", "2026-08-15", "",
		"4.0", "0.0", "未开始"
	};

	static const char *kRootCells[9] =
	{
		"事件响应示例任务", "EVT-001", "张三",
		"2026-08-07", "2026-08-20", "",
		"10.0", "0.0", "进行中"
	};

	QtTreeNode child;
	memset(&child, 0, sizeof(child));
	child.cells = kChildCells;
	child.cellCount = 9;
	child.progress = 0;
	child.checkable = 1;

	QtTreeNode root;
	memset(&root, 0, sizeof(root));
	root.cells = kRootCells;
	root.cellCount = 9;
	root.progress = 0;
	root.checkable = 1;
	root.expanded = 1;
	root.childCount = 1;
	root.children = &child;

	_treeTableHost.SetData(&root, 1);

	return TRUE;
}
